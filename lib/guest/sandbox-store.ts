function generateGuestTasks(state: GuestSandboxState, event: MinistryEvent) {
  const tasks = defaultTemplateTasks[event.type].map((template) => {
    const task: ActiveTask = {
      id: `guest_task_${event.id}_${template.id}`,
      eventId: event.id,
      taskTitle: template.taskTitle,
      dueDate: addDays(event.startTime, template.timelineOffsetDays),
      assignedUserId: state.users.find((user) => user.role === template.roleAssigned)?.id ?? state.users[0].id,
      status: "todo",
      autoGenerated: true,
      timelineOffsetDays: template.timelineOffsetDays,
      notes: "Guest sandbox workflow task."
    };
    state.tasks.push(task);
    return task;
  });
  event.autoGeneratedTimeline = tasks.map((task) => task.id);
  syncGuestEventStatus(state, event.id);
}

