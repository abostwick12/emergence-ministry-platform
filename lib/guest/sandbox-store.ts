function syncGuestEventStatus(state: GuestSandboxState, eventId: string) {
  const event = state.events.find((item) => item.id === eventId);
  if (!event) return;
  const nextStatus = deriveEventStatusFromTasks(state.tasks.filter((task) => task.eventId === eventId));
  if (nextStatus) event.status = nextStatus;
}

function recordGuestActivity(state: GuestSandboxState, input: Omit<ActivityLog, "id" | "actorId" | "timestamp">) {
  state.activity.unshift({
    id: uid("guest_act"),
    actorId: "guest_admin",
    timestamp: new Date().toISOString(),
    ...input
  });
}
