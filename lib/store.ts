function recordActivity(input: Omit<ActivityLog, "id" | "actorId" | "timestamp">) {
  const item: ActivityLog = {
    id: uid("act"),
    actorId: actorId(),
    timestamp: new Date().toISOString(),
    ...input
  };
  activity.unshift(item);
  return item;
}

function generateTasksForEvent(event: MinistryEvent) {
  const templateTasks = defaultTemplateTasks[event.type];
  const generated = templateTasks.map((template) => {
    const assignee = users.find((user) => user.role === template.roleAssigned) ?? users[0];
    const task: ActiveTask = {
      id: `task_${event.id}_${template.id}`,
      eventId: event.id,
      taskTitle: template.taskTitle,
      dueDate: addDays(event.startTime, template.timelineOffsetDays),
      assignedUserId: assignee.id,
      status: "todo",
      autoGenerated: true,
      timelineOffsetDays: template.timelineOffsetDays
    };
    tasks.push(task);
    recordActivity({
      type: "task_generated",
      eventId: event.id,
      taskId: task.id,
      message: `Generated task: ${task.taskTitle}`,
      metadata: {
        dueDate: task.dueDate,
        timelineOffsetDays: task.timelineOffsetDays
      }
    });
    return task;
  });

  event.autoGeneratedTimeline = generated.map((task) => task.id);
  return generated;
}

if (!store.initialized) {
  events.forEach((event) => {
    generateTasksForEvent(event);
    recordActivity({
      type: "event_created",
      eventId: event.id,
      message: `Created event: ${event.title}`,
      metadata: { type: event.type }
    });
  });
  store.initialized = true;
}

