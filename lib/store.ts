export function updateEvent(
  id: string,
  input: Partial<
    Pick<MinistryEvent, "title" | "description" | "startTime" | "endTime" | "location" | "targetGroup" | "budgetTarget" | "budgetActual" | "volunteersNeeded" | "priority" | "contactOwnerId" | "notes">
  >
) {
  const event = getEvent(id);
  if (!event) return undefined;

  const changedFields: string[] = [];

  (["title", "description", "startTime", "endTime", "location", "targetGroup", "budgetTarget", "budgetActual", "volunteersNeeded", "priority", "contactOwnerId", "notes"] as const).forEach((field) => {
    if (input[field] !== undefined && input[field] !== event[field]) {
      changedFields.push(field);
    }
  });

  Object.assign(event, input);

  if (changedFields.length > 0) {
    recordActivity({
      type: input.notes !== undefined ? "event_notes_updated" : "event_updated",
      eventId: event.id,
      message: input.notes !== undefined ? `Updated event notes: ${event.title}` : `Updated event information: ${event.title}`,
      metadata: { fields: changedFields.join(", ") }
    });
  }

  return getWorkspace(event.id);
}

export function updateTask(
  id: string,
  input: Partial<Pick<ActiveTask, "taskTitle" | "dueDate" | "assignedUserId" | "status" | "notes">>
) {
  const task = tasks.find((item) => item.id === id);
  if (!task) return undefined;

  const previousStatus = task.status;
  const previousOwner = task.assignedUserId;
  const previousTitle = task.taskTitle;
  const previousDueDate = task.dueDate;
  const previousNotes = task.notes;

  Object.assign(task, input);

  if (input.status && input.status !== previousStatus) {
    recordActivity({
      type: "task_status_changed",
      eventId: task.eventId,
      taskId: task.id,
      message: `Moved task to ${input.status.replace("_", " ")}: ${task.taskTitle}`,
      metadata: { from: previousStatus, to: input.status }
    });
  }

  if (input.assignedUserId && input.assignedUserId !== previousOwner) {
    recordActivity({
      type: "task_owner_changed",
      eventId: task.eventId,
      taskId: task.id,
      message: `Changed owner for task: ${task.taskTitle}`,
      metadata: { from: previousOwner, to: input.assignedUserId }
    });
  }

  if (input.taskTitle && input.taskTitle !== previousTitle) {
    recordActivity({
      type: "task_edited",
      eventId: task.eventId,
      taskId: task.id,
      message: `Edited task title: ${input.taskTitle}`,
      metadata: { from: previousTitle, to: input.taskTitle }
    });
  }

  if (input.dueDate && input.dueDate !== previousDueDate) {
    recordActivity({
      type: "task_edited",
      eventId: task.eventId,
      taskId: task.id,
      message: `Changed due date for task: ${task.taskTitle}`,
      metadata: { from: previousDueDate, to: input.dueDate }
    });
  }

  if (input.notes !== undefined && input.notes !== previousNotes) {
    recordActivity({
      type: "task_notes_updated",
      eventId: task.eventId,
      taskId: task.id,
      message: `Updated task notes: ${task.taskTitle}`,
      metadata: { hasNotes: Boolean(input.notes?.trim()) }
    });
  }

  return task;
}

export function generateCommunicationPreview(eventId: string) {
  const event = getEvent(eventId);
  if (!event) return undefined;

  const eventTasks = tasks.filter((task) => task.eventId === eventId);
  const openTasks = eventTasks.filter((task) => task.status !== "done");
  const missing = getMissingInformation(event, expenses.filter((expense) => expense.eventId === eventId));
  const missingNote = missing.length
    ? `Details still being confirmed: ${missing.map((item) => item.label).join(" ")}`
    : "All core event information is ready for review.";
  const locationLine = event.location ?? "Location is still being finalized.";
  const dateLine = new Date(event.startTime).toLocaleString();
  const taskLine = `${openTasks.length} open task${openTasks.length === 1 ? "" : "s"} remain before this event is ready.`;
  const budgetLine = event.budgetTarget ? `Budget target: $${event.budgetTarget.toLocaleString()}.` : "Budget target is still being confirmed.";
  const registrationLine = "Registration details are still being confirmed.";
  const packingLine =
    event.type === "retreat" || event.type === "camp"
      ? "Packing list is not available yet."
      : "Packing list is not needed for this event type in MVP 1.";

  const createdAt = new Date().toISOString();
  const previews: CommunicationPackage[] = [
    {
      id: uid("comm"),
      eventId,
      type: "parent_email",
      payload: {
        subject: `Parent email preview: ${event.title}`,
        body: `Preview only — not sent.\n\nHi families,\n\nHere is the current preview for ${event.title}, a ${event.type} event.\n\nSummary: ${event.description || "Event summary is still being finalized."}\nDate/time: ${dateLine}\nLocation: ${locationLine}\n${registrationLine}\n${packingLine}\nWhat families need to know: ${missingNote}\n${budgetLine}\nNext step: Watch for the final details from the ministry team before making plans.`
      },
      status: "preview",
      createdAt
    },
    {
      id: uid("comm"),
      eventId,
      type: "leader_brief",
      payload: {
        subject: `Leader announcement preview: ${event.title}`,
        body: `Preview only — not sent.\n\nLeader heads up for ${event.title}: ${event.description || "Event summary is still being finalized."}\n\nDate/time: ${dateLine}\nLocation: ${locationLine}\nVolunteer/task awareness: ${taskLine}\nMissing info: ${missingNote}\n${registrationLine}\nNext step for leaders: Review your assigned tasks and flag anything blocked.`
      },
      status: "preview",
      createdAt
    },
    {
      id: uid("comm"),
      eventId,
      type: "student_announcement",
      payload: {
        subject: `Blast text preview: ${event.title}`,
        body: `Preview only — not sent.\n\n${event.title}: ${dateLine}. ${event.location ? `Meet at ${event.location}.` : "Location is still being finalized."} ${missing.length ? "More details coming soon." : "Watch for final reminders soon."}`
      },
      status: "preview",
      createdAt
    }
  ];

  communications.unshift(...previews);
  recordActivity({
    type: "communication_preview_generated",
    eventId,
    message: `Generated communication previews for ${event.title}`,
    metadata: { previewCount: previews.length, sent: false }
  });
  return previews;
}

export function runIntegrationStub(eventId: string, type: "google_drive" | "propresenter" | "google_calendar" | "planning_center") {
  const event = getEvent(eventId);
  if (!event) return undefined;

  const log = integrationAdapters[type].runStubAction(event);
  integrationLogs.unshift(log);

  if (type === "google_drive") {
    event.googleDriveFolderId = `stub-drive-${event.id}`;
  }

  if (type === "propresenter") {
    event.proPresenterPlaylistId = `stub-pro-${event.id}`;
  }

  recordActivity({
    type: "integration_stub_action",
    eventId,
    message: `Stub Mode: ${log.details.action} for ${event.title}`,
    metadata: { integrationType: type, status: log.status }
  });

  return log;
}

export function getBudget(eventId: string) {
  const event = getEvent(eventId);
  const eventExpenses = expenses.filter((expense) => expense.eventId === eventId);
  const spent = eventExpenses.reduce((sum, expense) => sum + expense.amount, 0);
  return {
    eventId,
    target: event?.budgetTarget ?? 0,
    spent,
    remaining: (event?.budgetTarget ?? 0) - spent,
    expenses: eventExpenses
  };
}

export function addExpense(input: { eventId: string; categoryId: string; amount: number; description: string }) {
  const expense: EventExpense = {
    id: uid("exp"),
    timestamp: new Date().toISOString(),
    ...input
  };
  expenses.unshift(expense);
  return expense;
}

export function getWorkspace(eventId: string): EventWorkspace | undefined {
  const event = getEvent(eventId);
  if (!event) return undefined;

  const eventExpenses = expenses.filter((expense) => expense.eventId === eventId);

  return {
    event,
    tasks: tasks.filter((task) => task.eventId === eventId),
    communications: communications.filter((item) => item.eventId === eventId),
    integrationLogs: integrationLogs.filter((log) => log.eventId === eventId),
    expenses: eventExpenses,
    missingInformation: getMissingInformation(event, eventExpenses),
    activity: activity.filter((item) => item.eventId === eventId)
  };
}

